package com.example.data.local

import android.content.Context
import android.content.SharedPreferences
import android.provider.Settings
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import android.util.Log
import java.nio.charset.StandardCharsets
import java.security.KeyStore
import java.util.Locale
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Hardware-backed local credential vault for remembered operator logins on this device.
 *
 * Security properties:
 * - Encrypts passwords with an Android Keystore AES-256-GCM key (`AES/GCM/NoPadding`, 128-bit tag).
 * - Uses randomized encryption (fresh 12-byte IV generated by Keystore per write).
 * - Binds every entry to the device scope and normalized username via GCM Additional Authenticated Data (AAD).
 * - Never writes plaintext or weakly encoded credentials to disk if Keystore is unavailable.
 * - Never logs raw passwords, decrypted values, or ciphertexts.
 */
class SavedCredentialsVault(context: Context) {

    private val appContext = context.applicationContext

    private val prefs: SharedPreferences? = runCatching {
        appContext.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
    }.onFailure { err ->
        Log.e(TAG, "Failed opening credentials vault SharedPreferences", err)
    }.getOrNull()

    private val deviceScope: String by lazy {
        runCatching {
            val androidId = Settings.Secure.getString(
                appContext.contentResolver,
                Settings.Secure.ANDROID_ID
            )?.trim()?.takeIf { it.isNotEmpty() } ?: "local_device"
            "etx_vault_$androidId"
        }.getOrDefault("etx_vault_local_device")
    }

    @Synchronized
    fun savePassword(accountName: String, rawPassword: String): Boolean {
        val cleanAccount = OperatorIdentityFormatter.sanitizeUsername(accountName)
        if (cleanAccount.isEmpty() || rawPassword.isEmpty()) return false
        val encrypted = encryptForKey(rawPassword, aadForAccount(cleanAccount)) ?: return false
        return commitEdit {
            putString(prefKeyForAccount(cleanAccount), encrypted)
        }
    }

    @Synchronized
    fun getSavedPassword(accountName: String): String? {
        val cleanAccount = OperatorIdentityFormatter.sanitizeUsername(accountName)
        if (cleanAccount.isEmpty()) return null
        val prefKey = prefKeyForAccount(cleanAccount)
        val stored = safeGetString(prefKey) ?: return null
        val decrypted = decryptForKey(stored, aadForAccount(cleanAccount))
        if (decrypted == null) {
            // Safely purge corrupted or keystore-invalidated entry without crashing
            commitEdit { remove(prefKey) }
            return null
        }
        return decrypted
    }

    @Synchronized
    fun hasSavedPassword(accountName: String): Boolean {
        val cleanAccount = OperatorIdentityFormatter.sanitizeUsername(accountName)
        if (cleanAccount.isEmpty()) return false
        return !safeGetString(prefKeyForAccount(cleanAccount)).isNullOrBlank()
    }

    @Synchronized
    fun getSavedCredentialUsernames(): Set<String> {
        val allEntries = runCatching { prefs?.all }.getOrNull() ?: return emptySet()
        val result = LinkedHashSet<String>()
        allEntries.forEach { (key, value) ->
            if (key.startsWith(KEY_ACCOUNT_PREFIX) && value is String && value.isNotBlank()) {
                val username = key.removePrefix(KEY_ACCOUNT_PREFIX).lowercase(Locale.US)
                if (username.isNotBlank()) {
                    result.add(username)
                }
            }
        }
        return result
    }

    @Synchronized
    fun removePassword(accountName: String) {
        val cleanAccount = OperatorIdentityFormatter.sanitizeUsername(accountName)
        if (cleanAccount.isEmpty()) return
        commitEdit {
            remove(prefKeyForAccount(cleanAccount))
        }
    }

    /**
     * Temporarily encrypts and holds the password while a newly registered account
     * waits for 1-time Firebase email verification.
     */
    @Synchronized
    fun savePendingPassword(accountName: String, rawPassword: String): Boolean {
        val cleanAccount = OperatorIdentityFormatter.sanitizeUsername(accountName)
        if (cleanAccount.isEmpty() || rawPassword.isEmpty()) return false
        val encrypted = encryptForKey(rawPassword, aadForPending(cleanAccount)) ?: return false
        return commitEdit {
            putString(KEY_PENDING_ACCOUNT, cleanAccount)
            putString(KEY_PENDING_PASSWORD, encrypted)
        }
    }

    /**
     * Promotes a temporarily encrypted pending registration password into the permanent
     * account vault entry once email verification succeeds, then clears pending storage.
     */
    @Synchronized
    fun promotePendingPassword(accountName: String): Boolean {
        val cleanAccount = OperatorIdentityFormatter.sanitizeUsername(accountName)
        if (cleanAccount.isEmpty()) {
            clearPendingPassword()
            return false
        }
        val pendingAccount = safeGetString(KEY_PENDING_ACCOUNT)
        val pendingCipher = safeGetString(KEY_PENDING_PASSWORD)
        clearPendingPassword()
        if (pendingAccount.isNullOrBlank() ||
            pendingCipher.isNullOrBlank() ||
            !pendingAccount.equals(cleanAccount, ignoreCase = true)
        ) {
            return false
        }
        val decrypted = decryptForKey(pendingCipher, aadForPending(cleanAccount)) ?: return false
        return savePassword(cleanAccount, decrypted)
    }

    @Synchronized
    fun clearPendingPassword() {
        commitEdit {
            remove(KEY_PENDING_ACCOUNT)
            remove(KEY_PENDING_PASSWORD)
        }
    }

    private fun prefKeyForAccount(cleanAccount: String): String =
        "$KEY_ACCOUNT_PREFIX${cleanAccount.lowercase(Locale.US)}"

    private fun aadForAccount(cleanAccount: String): ByteArray =
        "etx_cred_v1|$deviceScope|acct|${cleanAccount.lowercase(Locale.US)}"
            .toByteArray(StandardCharsets.UTF_8)

    private fun aadForPending(cleanAccount: String): ByteArray =
        "etx_cred_v1|$deviceScope|pending|${cleanAccount.lowercase(Locale.US)}"
            .toByteArray(StandardCharsets.UTF_8)

    private fun safeGetString(key: String): String? {
        return runCatching { prefs?.getString(key, null) }.getOrNull()
    }

    private fun commitEdit(block: SharedPreferences.Editor.() -> Unit): Boolean {
        return runCatching {
            val editor = prefs?.edit() ?: return false
            editor.block()
            val committed = runCatching { editor.commit() }.getOrDefault(false)
            if (!committed) {
                editor.apply()
            }
            true
        }.onFailure { err ->
            Log.w(TAG, "Failed writing to credentials vault", err)
        }.getOrDefault(false)
    }

    private fun encryptForKey(plaintext: String, aad: ByteArray): String? {
        return runCatching {
            val key = getOrCreateKeystoreKey()
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, key)
            cipher.updateAAD(aad)
            val iv = cipher.iv
            val cipherText = cipher.doFinal(plaintext.toByteArray(StandardCharsets.UTF_8))
            PREFIX_KS_GCM + packIvAndCipherText(iv, cipherText)
        }.onFailure { err ->
            Log.w(TAG, "Keystore AES-GCM encryption unavailable for credential vault", err)
        }.getOrNull()
    }

    private fun decryptForKey(payload: String, aad: ByteArray): String? {
        if (!payload.startsWith(PREFIX_KS_GCM)) return null
        return runCatching {
            val (iv, cipherText) = unpackIvAndCipherText(payload.removePrefix(PREFIX_KS_GCM))
                ?: return null
            val key = getExistingKeystoreKey() ?: return null
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(GCM_TAG_BITS, iv))
            cipher.updateAAD(aad)
            String(cipher.doFinal(cipherText), StandardCharsets.UTF_8)
        }.onFailure { err ->
            Log.w(TAG, "Keystore AES-GCM decryption failed safely for credential vault", err)
        }.getOrNull()
    }

    private fun getExistingKeystoreKey(): SecretKey? {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }
        return keyStore.getKey(KEY_ALIAS, null) as? SecretKey
    }

    private fun getOrCreateKeystoreKey(): SecretKey {
        getExistingKeystoreKey()?.let { return it }
        val keyGenerator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE_PROVIDER)
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setRandomizedEncryptionRequired(true)
            .setKeySize(256)
            .build()
        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }

    private fun packIvAndCipherText(iv: ByteArray, cipherText: ByteArray): String {
        val combined = ByteArray(1 + iv.size + cipherText.size)
        combined[0] = iv.size.toByte()
        System.arraycopy(iv, 0, combined, 1, iv.size)
        System.arraycopy(cipherText, 0, combined, 1 + iv.size, cipherText.size)
        return Base64.encodeToString(combined, Base64.NO_WRAP)
    }

    private fun unpackIvAndCipherText(encoded: String): Pair<ByteArray, ByteArray>? {
        return runCatching {
            val combined = Base64.decode(encoded, Base64.NO_WRAP)
            if (combined.size < 2) return null
            val ivLen = combined[0].toInt() and 0xFF
            if (ivLen < 12 || combined.size <= 1 + ivLen) return null
            val iv = combined.copyOfRange(1, 1 + ivLen)
            val cipherText = combined.copyOfRange(1 + ivLen, combined.size)
            iv to cipherText
        }.getOrNull()
    }

    companion object {
        private const val TAG = "SavedCredentialsVault"
        private const val PREFS_NAME = "etx_saved_credentials_vault"
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val KEY_ALIAS = "etx_saved_credentials_aes_gcm_v1"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_BITS = 128
        private const val PREFIX_KS_GCM = "ksgcm1:"
        private const val KEY_ACCOUNT_PREFIX = "pwd_v1_"
        private const val KEY_PENDING_ACCOUNT = "pending_reg_account"
        private const val KEY_PENDING_PASSWORD = "pending_reg_pwd"
    }
}
